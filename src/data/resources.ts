/** Converts a resource title to a URL-safe slug matching the /resources/:slug route. */
function slugify(title: string): string {
  return title
    .toLowerCase()
    .replace(/['']/g, '')           // remove apostrophes (smart + straight)
    .replace(/[^a-z0-9]+/g, '-')   // replace non-alphanumeric runs with hyphens
    .replace(/^-+|-+$/g, '');      // trim leading/trailing hyphens
}

