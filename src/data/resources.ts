export const resourcesData: ResourceItem[] = baseResourcesData.map((res) => {
  const link = officialResourceLinks.find((v) => v.originalTitle === res.title);
  const slug = slugify(res.title);
  const content = resourceContentMap[res.title];
  return {
    ...res,
    // Official heading replaces the card title on the card
    displayTitle: link?.displayTitle ?? res.title,
    // Attribution label, e.g. "Salesforce", "Microsoft"
    sourceName: link?.sourceName ?? null,
    // officialDate: null = hide date; string = show; undefined = fall back to publishDate
    officialDate: link !== undefined ? link.officialDate : res.publishDate,
    // External source URL (opened from the detail page, not directly from the card)
    externalUrl: link?.externalUrl ?? null,
    // Every resource always has an internal page at /resources/:slug
    internalPath: `/resources/${slug}`,
    // Structured content body
    content: content,
  };
});


